@dataclass(frozen=True)
class Remediation:
    fix: str
    claim_type: str
    severity: Severity
    status: str | None
    scenario_id: str
    scenario_title: str
    approval: Approval | None = None
    simulated_history: tuple[Approval, ...] = ()

    def html(self) -> str:
        # Match the viewer's encodeURIComponent hash routing.
        fragment = quote(self.scenario_id, safe="-_.!~*'()")
        fix = escape(self.fix)
        if self.approval is not None:
            label = APPROVAL_LABELS[self.approval.action]
            fix += f"<br /><strong>{label}</strong>"
            if self.simulated_history:
                fix += f"<br />{escape(self.approval.actor)} · {escape(self.approval.note)}"
            if len(self.simulated_history) > 1:
                entries = "".join(
                    f"<li>{APPROVAL_LABELS[entry.action]} · {escape(entry.actor)}"
                    f" · {escape(entry.note)} · {entry.created_at.isoformat()}</li>"
                    for entry in self.simulated_history
                )
                fix += f"<details><summary>Approval history</summary><ol>{entries}</ol></details>"
        return ROW.format(
            fix=fix,
            claim_type=escape(self.claim_type),
            severity=escape(self.severity),
            href=escape(f"index.html#{fragment}"),
            title=escape(self.scenario_title),
        )


def remediation_rows(
    data: Path,
    conn: sqlite3.Connection | None = None,
    *,
    simulated_approvals: tuple[Approval, ...] = (),
) -> list[Remediation]:
    scenarios = {}
    for scenario in json.loads((data / "scenarios.json").read_bytes()):
        run = json.loads((data / f"run-{scenario['id']}.json").read_bytes())
        scenarios[run["audit_id"]] = scenario["id"], scenario["title"]

    by_audit: dict[str, list[Approval]] = defaultdict(list)
    for approval in simulated_approvals:
        by_audit[approval.audit_id].append(approval)

    rows = []
    for audit_id, (scenario_id, title) in sorted(scenarios.items()):
        report = AuditReport.model_validate_json((data / f"audit-{audit_id}.json").read_bytes())
        approvals = list_approvals(conn, audit_id) if conn is not None else by_audit[audit_id]
        decisions: dict[tuple[str, str], Approval] = {}
        history: dict[tuple[str, str], list[Approval]] = defaultdict(list)
        for approval in approvals:
            current = decisions.get(approval.target)
            # Acknowledgement adds context without reopening a closed task.
            if current is None or (
                current.action != "resolve" and approval.action != "acknowledge"
            ):
                decisions[approval.target] = approval
            if conn is None:
                history[approval.target].append(approval)
        for item in audit_items(report):
            _, collection, index = item.result_pointer.split("/")
            if collection == "findings":
                result = report.findings[int(index)]
                claim_type, status = f"Finding · {result.kind}", None
                target = ("finding", result.finding_id)
            else:
                result = report.verdicts[int(index)]
                target = ("claim", result.claim.claim_id)
                if (
                    target not in decisions
                    and scenario_id in RECHECKS
                    and isinstance(result.claim, AppointmentBooked)
                ):
                    continue
                claim_type, status = result.claim.type, result.status
            rows.append(
                Remediation(
                    result.remediation or "No suggested fix recorded.",
                    claim_type,
                    result.severity,
                    status,
                    scenario_id,
                    title,
                    decisions.get(target),
                    tuple(history.get(target, ())),
                )
            )

    # Findings have no verdict status and follow verdicts at the same severity.
    return sorted(
        rows,
        key=lambda row: (
            -SEVERITY_RANK[row.severity],
            row.status is None,
            row.status or "",
        ),
    )


def replay_recheck(scenario_id: str, offset: timedelta) -> tuple[AuditReport, AuditReport]:
    original_file = DATA / f"audit-aud-{scenario_id}.json"
    original = AuditReport.model_validate_json(original_file.read_bytes())
    original_verdict = next(v for v in original.verdicts if isinstance(v.claim, AppointmentBooked))
    claim = original_verdict.claim
    assert isinstance(claim, AppointmentBooked)
    assert original.seal is not None
    scenario = BY_ID[scenario_id]
    (step,) = scenario.steps
    assert isinstance(step, Book)
    world = build_world(scenario)
    with closing(world.store):
        call = run_suspect(scenario, world).call
        assert call == original.call

        # Simulate a call-linked retry after the first audit, with no auditor writes.
        retried_at = original.created_at + timedelta(seconds=1)
        writer = world.store.session(f"{call.agent_id}:{call.call_id}", lambda: retried_at)
        (patient,) = writer.crm.find_patients(phone=claim.patient.phone)
        writer.calendar.create_appointment(
            patient_id=patient.id,
            provider=claim.provider if claim.provider is not None else step.provider,
            start=claim.start + offset,
            duration_min=claim.duration_min or step.duration_min,
            reason=claim.reason if claim.reason is not None else step.reason,
        )
        audited_at = retried_at + timedelta(seconds=1)
        reader = world.store.session("auditor", lambda: audited_at)
        # Include the simulated retry in this re-check's call evidence window.
        report = Auditor(
            reader,
            clinic=CLINIC,
            extractor=RuleBasedExtractor(),
            sealer=Sealer(SEALING_KEY),
            clock=lambda: audited_at,
            grace=audited_at - call.ended_at,
        ).audit(
            call,
            audit_id=f"aud-{scenario_id}-recheck",
            prev_hash=original.seal.chain_hash,
        )
    return original, report


def recheck_html(scenario_id: str, original: AuditReport, report: AuditReport) -> str:
    before = next(v for v in original.verdicts if isinstance(v.claim, AppointmentBooked))
    after = next(v for v in report.verdicts if v.claim.claim_id == before.claim.claim_id)
    state = "Closed" if after.status is VerdictStatus.VERIFIED else "Still open"
    evidence = ", ".join(f"{item.source} · {item.ref}" for item in after.evidence)
    return f"""    <article>
      <h3>{escape(BY_ID[scenario_id].title)}</h3>
      <p>Initially open · {escape(before.status)}</p>
      <p>{escape(before.remediation or "")}</p>
      <p><strong class="{"closed" if state == "Closed" else "open"}">{state}</strong>
        · <strong>{escape(after.status)}</strong></p>
      <p>{escape(after.summary)}</p>
      <p>Re-check evidence · {escape(evidence)}</p>
      <a href="data/audit-{report.audit_id}.json">{report.audit_id}</a>
      <a href="index.html#{scenario_id}">Original call</a>
    </article>"""


def replay_apply_fix() -> tuple[AuditReport, Approval, AuditReport]:
    scenario = BY_ID[APPLY_FIX_SCENARIO]
    original = AuditReport.model_validate_json(
        (DATA / f"audit-aud-{scenario.id}.json").read_bytes()
    )
    (before,) = (v for v in original.verdicts if isinstance(v.claim, AppointmentBooked))
    assert before.status is VerdictStatus.MISMATCH
    world = build_world(scenario)
    with closing(world.store):
        assert run_suspect(scenario, world).call == original.call
        app = create_app(Settings(signing_key=SEALING_KEY))
        app.state.sor.close()
        app.state.sor = world.store
        with closing(app.state.store), TestClient(app) as client:
            # Seed a standalone ledger with the original report under a replay-specific ID.
            original = app.state.store.append(
                original.model_copy(update={"audit_id": f"{original.audit_id}-apply-fix-before"}),
                app.state.sealer,
            )
            path = f"/audit/{original.audit_id}"
            approved_at = original.created_at + timedelta(seconds=1)
            with patch("subpoena.api.approvals.utcnow", return_value=approved_at):
                response = client.post(
                    f"{path}/approvals",
                    json={
                        "claim_id": before.claim.claim_id,
                        "action": "resolve",
                        "actor": "Jordan Lee, front desk",
                        "note": "Approved booking the time promised to the caller.",
                    },
                )
            approval = Approval.model_validate(response.raise_for_status().json()["data"])

            # Freeze the endpoint's clock and generated report ID for the static export.
            fixed_at = approved_at + timedelta(seconds=1)
            replay_id = uuid5(NAMESPACE_URL, original.audit_id)
            with (
                patch("subpoena.api.app.utcnow", return_value=fixed_at),
                patch("subpoena.auditor.engine.uuid", SimpleNamespace(uuid4=lambda: replay_id)),
            ):
                response = client.post(f"{path}/claims/{before.claim.claim_id}/fix")
            checked_id = response.raise_for_status().json()["data"]["audit_id"]
            response = client.get(f"/audit/{checked_id}/report")
            checked = AuditReport.model_validate(response.raise_for_status().json()["data"])
    return original, approval, checked


def apply_fix_html(original: AuditReport, approval: Approval, checked: AuditReport) -> str:
    (after,) = checked.verdicts
    assert after.status is VerdictStatus.VERIFIED
    before = next(v for v in original.verdicts if v.claim.claim_id == after.claim.claim_id)
    (receipt,) = (event.message for event in checked.trail if event.stage == "fix")
    return f"""    <article>
      <h3>{escape(BY_ID[APPLY_FIX_SCENARIO].title)}</h3>
      <p>Before fix · <strong class="open">{escape(before.status)}</strong></p>
      <p>Simulated resolve approval · {escape(approval.actor)} · {escape(approval.note)}</p>
      <p>Fix receipt · {escape(receipt)}</p>
      <p>After re-check · <strong class="closed">{escape(after.status)}</strong></p>
      <p>{escape(after.summary)}</p>
      <a href="data/audit-{original.audit_id}.json">Sealed report before fix</a>
      <a href="data/approval-{original.audit_id}.json">Simulated approval record</a>
      <a href="data/audit-{checked.audit_id}.json">Sealed fix and re-check report</a>
    </article>"""


def write_report(data: Path, report: AuditReport) -> None:
    (data / f"audit-{report.audit_id}.json").write_text(
        json.dumps(report.model_dump(mode="json"), indent=1), encoding="utf-8", newline="\n"
    )
    (data / f"report-{report.audit_id}.md").write_text(
        render_markdown(report), encoding="utf-8", newline="\n"
    )


def export(
    out: Path = DEFAULT_OUT,
    *,
    approvals_db: Path | None = None,
    approvals_json: Path | None = None,
) -> None:
    if approvals_db is not None and approvals_json is not None:
        raise ValueError("provide only one approval source")
    simulated_approvals = ()
    if approvals_db is None:
        fixture = approvals_json if approvals_json is not None else DEFAULT_APPROVALS
        simulated_approvals = TypeAdapter(tuple[Approval, ...]).validate_json(fixture.read_bytes())
    output_data = out / "data"
    output_data.mkdir(parents=True, exist_ok=True)
    examples = []
    for scenario_id, offset in RECHECKS.items():
        original, report = replay_recheck(scenario_id, offset)
        write_report(output_data, report)
        examples.append(recheck_html(scenario_id, original, report))

    original, approval, checked = replay_apply_fix()
    write_report(output_data, original)
    write_report(output_data, checked)
    (output_data / f"approval-{original.audit_id}.json").write_text(
        approval.model_dump_json(indent=1, exclude_none=True), encoding="utf-8", newline="\n"
    )

    source = (
        closing(sqlite3.connect(f"{approvals_db.resolve().as_uri()}?mode=ro", uri=True))
        if approvals_db is not None
        else nullcontext()
    )
    with source as conn:
        if (
            conn is not None
            and not conn.execute(
                "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'approvals'"
            ).fetchone()
        ):
            conn = None  # Ledgers created before approvals have no approval history.
        remediations = remediation_rows(DATA, conn, simulated_approvals=simulated_approvals)
    page = PAGE
    if any(row.approval is not None for row in remediations):
        page = page.replace("Other open tasks", "Remediation tasks").replace(
            "A task closes only when the re-check passes.",
            "A task can be resolved by human approval or closed by a passing re-check.",
        )
    if any(row.simulated_history for row in remediations):
        page = page.replace(
            '  <h2 id="queue-items">Remediation tasks</h2>',
            '  <h2 id="queue-items">Remediation tasks</h2>\n'
            "  <p>Approvals show simulated human decisions in this replay.</p>",
        )
    rows = "\n".join(row.html() for row in remediations)
    (out / "remediation.html").write_text(
        page.replace("@RECHECKS@", "\n".join(examples))
        .replace("@APPLY_FIX@", apply_fix_html(original, approval, checked))
        .replace("@ROWS@", rows),
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Demo output directory")
    approvals = parser.add_mutually_exclusive_group()
    approvals.add_argument(
        "--approvals-db", type=Path, help="Read approval history from this audit ledger"
    )
    approvals.add_argument("--approvals-json", type=Path, help="Read simulated approval history")
    args = parser.parse_args()
    export(args.out, approvals_db=args.approvals_db, approvals_json=args.approvals_json)
