@dataclass(frozen=True)
class Remediation:
    fix: str
    claim_type: str
    severity: Severity
    status: str | None
    scenario_id: str
    scenario_title: str
    approval_action: ApprovalAction | None = None

    def html(self) -> str:
        # Match the viewer's encodeURIComponent hash routing.
        fragment = quote(self.scenario_id, safe="-_.!~*'()")
        fix = escape(self.fix)
        if self.approval_action is not None:
            label = {
                "acknowledge": "Acknowledged",
                "resolve": "Resolved",
                "dismiss": "Dismissed",
            }[self.approval_action]
            fix += f"<br><strong>{label}</strong>"
        return ROW.format(
            fix=fix,
            claim_type=escape(self.claim_type),
            severity=escape(self.severity),
            href=escape(f"index.html#{fragment}"),
            title=escape(self.scenario_title),
        )


def remediation_rows(data: Path, conn: sqlite3.Connection | None = None) -> list[Remediation]:
    scenarios = {}
    for scenario in json.loads((data / "scenarios.json").read_bytes()):
        run = json.loads((data / f"run-{scenario['id']}.json").read_bytes())
        scenarios[run["audit_id"]] = scenario["id"], scenario["title"]

    rows = []
    for audit_id, (scenario_id, title) in sorted(scenarios.items()):
        report = AuditReport.model_validate_json((data / f"audit-{audit_id}.json").read_bytes())
        actions: dict[tuple[str, str], ApprovalAction] = {}
        if conn is not None:
            for approval in list_approvals(conn, audit_id):
                current = actions.get(approval.target)
                # Acknowledgement adds context without reopening a closed task.
                if current != "resolve" and (current is None or approval.action != "acknowledge"):
                    actions[approval.target] = approval.action
        for item in audit_items(report):
            _, collection, index = item.result_pointer.split("/")
            if collection == "findings":
                result = report.findings[int(index)]
                claim_type, status = f"Finding · {result.kind}", None
                action = actions.get(("finding", result.finding_id))
            else:
                result = report.verdicts[int(index)]
                action = actions.get(("claim", result.claim.claim_id))
                if (
                    action is None
                    and scenario_id in RECHECKS
                    and isinstance(result.claim, AppointmentBooked)
                ):
                    continue
                claim_type, status = result.claim.type, result.status
            rows.append(
                Remediation(
                    result.remediation or "No suggested fix recorded.",
                    claim_type,
                    result.severity,
                    status,
                    scenario_id,
                    title,
                    action,
                )
            )

    # Findings have no verdict status and follow verdicts at the same severity.
    return sorted(
        rows,
        key=lambda row: (
            -SEVERITY_RANK[row.severity],
            row.status is None,
            row.status or "",
        ),
    )


def replay_recheck(scenario_id: str, offset: timedelta) -> tuple[AuditReport, AuditReport]:
    original_file = DATA / f"audit-aud-{scenario_id}.json"
    original = AuditReport.model_validate_json(original_file.read_bytes())
    original_verdict = next(v for v in original.verdicts if isinstance(v.claim, AppointmentBooked))
    claim = original_verdict.claim
    assert isinstance(claim, AppointmentBooked)
    assert original.seal is not None
    scenario = BY_ID[scenario_id]
    (step,) = scenario.steps
    assert isinstance(step, Book)
    world = build_world(scenario)
    with closing(world.store):
        call = run_suspect(scenario, world).call
        assert call == original.call

        # Simulate a call-linked retry after the first audit, with no auditor writes.
        retried_at = original.created_at + timedelta(seconds=1)
        writer = world.store.session(f"{call.agent_id}:{call.call_id}", lambda: retried_at)
        (patient,) = writer.crm.find_patients(phone=claim.patient.phone)
        writer.calendar.create_appointment(
            patient_id=patient.id,
            provider=claim.provider if claim.provider is not None else step.provider,
            start=claim.start + offset,
            duration_min=claim.duration_min or step.duration_min,
            reason=claim.reason if claim.reason is not None else step.reason,
        )
        audited_at = retried_at + timedelta(seconds=1)
        reader = world.store.session("auditor", lambda: audited_at)
        # Include the simulated retry in this re-check's call evidence window.
        report = Auditor(
            reader,
            clinic=CLINIC,
            extractor=RuleBasedExtractor(),
            sealer=Sealer(SEALING_KEY),
            clock=lambda: audited_at,
            grace=audited_at - call.ended_at,
        ).audit(
            call,
            audit_id=f"aud-{scenario_id}-recheck",
            prev_hash=original.seal.chain_hash,
        )
    return original, report


def recheck_html(scenario_id: str, original: AuditReport, report: AuditReport) -> str:
    before = next(v for v in original.verdicts if isinstance(v.claim, AppointmentBooked))
    after = next(v for v in report.verdicts if v.claim.claim_id == before.claim.claim_id)
    state = "Closed" if after.status is VerdictStatus.VERIFIED else "Still open"
    evidence = ", ".join(f"{item.source} · {item.ref}" for item in after.evidence)
    return f"""    <article>
      <h3>{escape(BY_ID[scenario_id].title)}</h3>
      <p>Initially open · {escape(before.status)}</p>
      <p>{escape(before.remediation or "")}</p>
      <p><strong class="{"closed" if state == "Closed" else "open"}">{state}</strong>
        · <strong>{escape(after.status)}</strong></p>
      <p>{escape(after.summary)}</p>
      <p>Re-check evidence · {escape(evidence)}</p>
      <a href="data/audit-{report.audit_id}.json">{report.audit_id}</a>
      <a href="index.html#{scenario_id}">Original call</a>
    </article>"""


def export(out: Path = DEFAULT_OUT, *, approvals_db: Path | None = None) -> None:
    output_data = out / "data"
    output_data.mkdir(parents=True, exist_ok=True)
    examples = []
    for scenario_id, offset in RECHECKS.items():
        original, report = replay_recheck(scenario_id, offset)
        (output_data / f"audit-{report.audit_id}.json").write_text(
            json.dumps(report.model_dump(mode="json"), indent=1), encoding="utf-8", newline="\n"
        )
        (output_data / f"report-{report.audit_id}.md").write_text(
            render_markdown(report), encoding="utf-8", newline="\n"
        )
        examples.append(recheck_html(scenario_id, original, report))

    source = (
        closing(sqlite3.connect(f"{approvals_db.resolve().as_uri()}?mode=ro", uri=True))
        if approvals_db is not None
        else nullcontext()
    )
    with source as conn:
        if (
            conn is not None
            and not conn.execute(
                "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'approvals'"
            ).fetchone()
        ):
            conn = None  # Ledgers created before approvals have no approval history.
        remediations = remediation_rows(DATA, conn)
    page = PAGE
    if any(row.approval_action is not None for row in remediations):
        page = page.replace("Other open tasks", "Remediation tasks").replace(
            "A task closes only when the re-check passes.",
            "A task can be resolved by human approval or closed by a passing re-check.",
        )
    rows = "\n".join(row.html() for row in remediations)
    (out / "remediation.html").write_text(
        page.replace("@RECHECKS@", "\n".join(examples)).replace("@ROWS@", rows),
        encoding="utf-8",
        newline="\n",
    )


