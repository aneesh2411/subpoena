#!/usr/bin/env python3
"""Export the suspect agent's claim verdict counts from the baked demo audits."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from shutil import copyfile

from subpoena.scenarios.world import BASELINE_AGENT

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "demo"
SOURCE = DEFAULT_OUT / "data"
DATA_PATH = "data-scorecard/scorecard.json"
STATUSES = ("VERIFIED", "MISMATCH", "NOT_FOUND", "UNVERIFIABLE")


def export(out: Path = DEFAULT_OUT) -> None:
    audits = sorted(SOURCE.glob("audit-*.json"))
    if not audits:
        raise FileNotFoundError(f"No baked audits in {SOURCE}")

    by_claim_type: dict[str, dict[str, int]] = {}
    for path in audits:
        audit = json.loads(path.read_text(encoding="utf-8"))
        for verdict in audit["verdicts"]:
            claim_type = verdict["claim"]["type"]
            counts = by_claim_type.setdefault(claim_type, dict.fromkeys(STATUSES, 0))
            counts[verdict["status"]] += 1

    data = {"audits": len(audits), "by_claim_type": by_claim_type}
    data_file = out / DATA_PATH
    data_file.parent.mkdir(parents=True, exist_ok=True)
    data_file.write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    if out.resolve() != DEFAULT_OUT.resolve():
        copyfile(DEFAULT_OUT / "print.css", out / "print.css")
    (out / "scorecard.html").write_text(
        PAGE.replace("@DATA_PATH@", DATA_PATH).replace("@BASELINE_AGENT@", BASELINE_AGENT),
        encoding="utf-8",
        newline="\n",
    )


