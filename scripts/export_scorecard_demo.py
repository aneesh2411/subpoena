#!/usr/bin/env python3
"""Export the suspect agent's claim verdict counts from the baked demo audits."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "demo"
SOURCE = DEFAULT_OUT / "data"
DATA_PATH = "data-scorecard/scorecard.json"
STATUSES = ("VERIFIED", "MISMATCH", "NOT_FOUND", "UNVERIFIABLE")


def export(out: Path = DEFAULT_OUT) -> None:
    audits = sorted(SOURCE.glob("audit-*.json"))
    if not audits:
        raise FileNotFoundError(f"No baked audits in {SOURCE}")

    by_claim_type: dict[str, dict[str, int]] = {}
    for path in audits:
        audit = json.loads(path.read_text(encoding="utf-8"))
        for verdict in audit["verdicts"]:
            claim_type = verdict["claim"]["type"]
            counts = by_claim_type.setdefault(claim_type, dict.fromkeys(STATUSES, 0))
            counts[verdict["status"]] += 1

    data = {"audits": len(audits), "by_claim_type": by_claim_type}
    data_file = out / DATA_PATH
    data_file.parent.mkdir(parents=True, exist_ok=True)
    data_file.write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    (out / "scorecard.html").write_text(
        PAGE.replace("@DATA_PATH@", DATA_PATH), encoding="utf-8", newline="\n"
    )


PAGE = """<!doctype html>
<!-- Generated by scripts/export_scorecard_demo.py. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Agent honesty scorecard | Subpoena</title>
<style>
  :root {
    color-scheme: dark;
    --bg: #11181c; --card: #1a252b; --line: #384b53; --text: #eff3ee;
    --muted: #b1c1c5; --accent: #9cd8f1; --verified: #8bd9b4;
    --mismatch: #ffc095; --not-found: #ffa8ad;
    --mono: ui-monospace, Consolas, monospace;
  }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--text); font: 1rem/1.6 system-ui; }
  header { border-bottom: 1px solid var(--line); }
  .brand, main { max-width: 66rem; margin: auto; padding-inline: clamp(1rem, 4vw, 3rem); }
  .brand { padding-block: 1rem; font: 700 .9rem var(--mono); letter-spacing: .16em; }
  main { padding-block: clamp(2rem, 6vw, 5rem); }
  h1 { font-size: clamp(2.35rem, 7vw, 4.6rem); line-height: 1.05; letter-spacing: -.05em; }
  h1, h2, p, dl, dd { margin: 0; }
  h1 { margin-top: .75rem; }
  h2 { font: 700 1rem/1.4 var(--mono); overflow-wrap: anywhere; }
  a { color: var(--accent); }
  a:focus-visible { outline: 2px solid var(--accent); outline-offset: 4px; }
  .intro { max-width: 55ch; margin-block: 1rem; }
  .intro, #summary { color: var(--muted); }
  #summary { margin-top: 1.5rem; }
  .grid { display: grid; gap: .75rem; margin-top: .75rem; }
  .card { min-width: 0; padding: 1rem; background: var(--card);
    border: 1px solid var(--line); border-radius: .65rem; }
  dl { display: grid; grid-template-columns: repeat(2, minmax(0, 1fr)); gap: .65rem;
    margin-top: .75rem; padding-top: .75rem; border-top: 1px solid var(--line); }
  dt { font-size: .875rem; overflow-wrap: anywhere; }
  dd { font: 700 1.25rem/1.5 var(--mono); overflow-wrap: anywhere; }
  .VERIFIED { color: var(--verified); }
  .MISMATCH { color: var(--mismatch); }
  .NOT_FOUND { color: var(--not-found); }
  .UNVERIFIABLE { color: var(--muted); }
  @media (min-width: 48rem) {
    .grid { grid-template-columns: repeat(2, minmax(0, 1fr)); }
  }
</style>
</head>
<body>
<header><div class="brand">SUBPOENA</div></header>
<main>
  <a href="./">Back to audit demo</a>
  <h1>Agent honesty scorecard</h1>
  <p class="intro">How often did the suspect agent’s claims survive the audit?
    These counts show the auditor’s verdicts by claim type.
    See <a href="evals.html">evaluation results</a> for auditor accuracy.</p>
  <a href="@DATA_PATH@">Download the verdict counts</a>
  <p id="status" role="status">Loading the scorecard…</p>
  <noscript>Enable JavaScript to view the scorecard.</noscript>
  <p id="summary"></p>
  <div class="grid" id="scorecard"></div>
</main>
<script>
  const statuses = [
    ["VERIFIED", "Verified"],
    ["MISMATCH", "Mismatch"],
    ["NOT_FOUND", "Not found"],
    ["UNVERIFIABLE", "Unverifiable"],
  ];
  const statusLine = document.getElementById("status");

  function addText(parent, tag, text) {
    const element = document.createElement(tag);
    element.textContent = text;
    parent.append(element);
  }

  function render(data) {
    const cards = document.createDocumentFragment();
    let total = 0;
    for (const [claimType, counts] of Object.entries(data.by_claim_type)) {
      const card = document.createElement("section");
      card.className = "card";
      addText(card, "h2", claimType);
      const list = document.createElement("dl");
      for (const [status, label] of statuses) {
        const group = document.createElement("div");
        group.className = status;
        addText(group, "dt", label);
        addText(group, "dd", counts[status]);
        list.append(group);
        total += counts[status];
      }
      card.append(list);
      cards.append(card);
    }
    document.getElementById("summary").textContent =
      total + " claim verdicts across " + data.audits + " baked audits";
    document.getElementById("scorecard").append(cards);
    statusLine.hidden = true;
  }

  fetch("@DATA_PATH@")
    .then(response => {
      if (!response.ok) throw new Error("Could not load the verdict counts");
      return response.json();
    })
    .then(render)
    .catch(() => {
      statusLine.textContent = "Could not load the scorecard. "
        + "Serve this directory over HTTP with its data-scorecard folder beside the page.";
    });
</script>
</body>
</html>
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Demo output directory")
    export(parser.parse_args().out)
