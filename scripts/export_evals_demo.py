CALL_METRICS = (
    "Calls",
    "Strict call accuracy",
    "Claim-level precision",
    "Claim-level recall",
)


def percent(value: float | None) -> str:
    return "—" if value is None else f"{value:.2%}"


EXTRACTION_METRICS = ("Precision", "Recall", "Invented", "Missed")


def extraction_metrics(counts: dict) -> tuple[str, ...]:
    return (
        percent(counts["precision"]),
        percent(counts["recall"]),
        str(counts["fp"]),
        str(counts["fn"]),
    )


def call_metrics(result: dict) -> tuple[str, ...]:
    claims = result["claim_level"]
    return (
        str(result["calls"]),
        percent(result["call_strict_accuracy"]),
        percent(claims["precision"]),
        percent(claims["recall"]),
    )


def table(
    section_id: str,
    title: str,
    columns: tuple[str, ...],
    rows: list[tuple[str, ...]],
    *,
    description: str = "",
    keep_columns: bool = False,
) -> str:
    scroll_class = "table-scroll keep-columns" if keep_columns else "table-scroll"
    heading = "".join(f'<th scope="col">{escape(column)}</th>' for column in columns)
    body = []
    for label, *values in rows:
        cells = "".join(f"<td>{escape(value)}</td>" for value in values)
        body.append(f'        <tr role="row"><th scope="row">{escape(label)}</th>{cells}</tr>')
    return (
        f'  <section class="panel" aria-labelledby="{section_id}">\n'
        f'    <h2 id="{section_id}">{escape(title)}</h2>\n'
        + (f'    <p class="intro">{escape(description)}</p>\n' if description else "")
        + f'    <div class="{scroll_class}" tabindex="0" role="region" '
        f'aria-label="{escape(title)} table">\n'
        '      <table role="table">\n'
        f'        <thead role="rowgroup"><tr role="row">{heading}</tr></thead>\n'
        '        <tbody role="rowgroup">\n' + "\n".join(body) + "\n"
        "        </tbody>\n"
        "      </table>\n"
        "    </div>\n"
        "  </section>"
    )


# The positional golden scorer records mismatched and missing verdicts in this format.
EXPECTED_CLAIM_FAILURE = re.compile(
    r"(\w+)\[(\d+)\]: expected \w+, (?:got (\w+)|auditor saw no claim)"
)
KNOWN_GAPS = {scenario.id for scenario in GOLDEN if scenario.known_gap}


CLAIM_ACCURACY_COLUMNS = (
    "Claim type",
    "Golden claims",
    "Strict accuracy",
    "Safe rate",
    "Known gaps",
)


def claim_accuracy_rows(
    golden: dict, scenarios: tuple[Scenario, ...] = GOLDEN
) -> list[tuple[str, ...]]:
    mismatches = defaultdict(dict)
    for failure in golden["failures"]:
        for problem in failure["problems"]:
            match = EXPECTED_CLAIM_FAILURE.fullmatch(problem)
            if match:
                claim_type, index, actual = match.groups()
                mismatches[failure["scenario"]][claim_type, int(index)] = actual

    total, strict, safe, gaps = Counter(), Counter(), Counter(), Counter()
    for scenario in scenarios:
        positions = Counter()
        failures_by_position = mismatches[scenario.id]
        for claim_type, expected in scenario.expected_claims:
            position = claim_type, positions[claim_type]
            positions[claim_type] += 1
            total[claim_type] += 1
            if position not in failures_by_position:
                strict[claim_type] += 1
                safe[claim_type] += 1
                continue
            if failures_by_position[position] != "VERIFIED" or expected.value == "VERIFIED":
                safe[claim_type] += 1
            if scenario.known_gap:
                gaps[claim_type] += 1

    return [
        (
            claim_type,
            str(count),
            percent(strict[claim_type] / count),
            percent(safe[claim_type] / count),
            str(gaps[claim_type]),
        )
        for claim_type, count in sorted(total.items())
    ]


def claim_accuracy_by_version(results: dict) -> dict[str, list[tuple[str, ...]]]:
    return {
        version: claim_accuracy_rows(summary, GOLDEN_BY_AGENT_VERSION[version])
        for version, summary in {
            BASELINE_AGENT: results["golden"],
            **results.get("golden_variants", {}),
        }.items()
    }


def failures(suites: tuple[tuple[str, dict], ...]) -> str:
    lines = [
        '  <section class="panel failures" aria-labelledby="failing-scenarios">',
        '    <h2 id="failing-scenarios">Failing scenarios</h2>',
    ]
    for label, result in suites:
        lines.append(f"    <h3>{label}</h3>")
        if not result["failures"]:
            lines.append("    <p>No failures recorded.</p>")
            continue
        lines.append("    <ul>")
        for failure in result["failures"]:
            scenario = failure["scenario"]
            gap_label = " (known gap)" if scenario in KNOWN_GAPS else ""
            lines.append(f"      <li><strong>{escape(scenario)}</strong>{gap_label}<ul>")
            for problem in failure["problems"]:
                lines.append(f"        <li><code>{escape(problem)}</code></li>")
            lines.append("      </ul></li>")
        lines.append("    </ul>")
    lines.append("  </section>")
    return "\n".join(lines)


def render(
    results: dict,
    check_in_date: str | None,
    fingerprint: str,
    overrides: dict[str, int],
    fuzz_sweep: dict,
) -> str:
    golden = results["golden"]
    semantic = results["golden_v2_semantic"]
    baseline = results["baseline_naive_existence_check"]
    fuzz = results["fuzz"]
    fuzz_semantic = results["fuzz_v2_semantic"]
    claim_rows = claim_accuracy_by_version(results)
    sections = [
        table(
            "golden-results",
            "Golden results and naive baseline",
            ("Suite and system", *CALL_METRICS),
            [
                ("Golden · Subpoena", *call_metrics(golden)),
                *[
                    (f"Golden · {version}", *call_metrics(summary))
                    for version, summary in results.get("golden_variants", {}).items()
                ],
                ("Golden · Naive existence check", *call_metrics(baseline)),
                ("Golden v2-semantic · Subpoena", *call_metrics(semantic)),
            ],
        ),
        table(
            "claim-accuracy",
            "Auditor accuracy by claim type",
            CLAIM_ACCURACY_COLUMNS,
            claim_rows[BASELINE_AGENT],
            description=(
                "Agent version: receptionist-v1. Strict accuracy requires an exact verdict match. "
                "Safe rate counts expected "
                "claims without an incorrect VERIFIED verdict. A missing verdict lowers strict "
                "accuracy and still counts as safe. Known gaps count misses in labeled scenarios."
            ),
        ),
        *[
            table(
                f"claim-accuracy-{index}",
                f"Auditor accuracy by claim type · {version}",
                CLAIM_ACCURACY_COLUMNS,
                rows,
            )
            for index, (version, rows) in enumerate(claim_rows.items(), start=1)
            if version != BASELINE_AGENT
        ],
        table(
            "fuzz-pass-rates",
            "Fuzz pass rates",
            ("Mode", "Calls", "Seed", "Strict pass rate"),
            [
                (mode, str(run["calls"]), str(run["seed"]), percent(run["call_strict_accuracy"]))
                for mode, run in (("Fuzz", fuzz), ("Fuzz v2-semantic", fuzz_semantic))
            ],
        ),
        table(
            "fuzz-failure-shapes",
            "Fuzz failure shapes",
            ("Failure shape", "Failed calls", "Seeds (failed calls)"),
            [
                (
                    "\n".join(shape["discrepancies"]),
                    str(shape["failed_calls"]),
                    ", ".join(
                        f"{seed} ({count})" for seed, count in shape["failed_calls_by_seed"].items()
                    ),
                )
                for shape in fuzz_sweep["failure_shapes"]
            ]
            or [("None", "0", "—")],
        ),
        table(
            "human-overrides",
            "Overrides from simulated human decisions",
            ("Disposition", "Claims"),
            [
                ("Confirmed", str(overrides["confirmed"])),
                ("Overturned", str(overrides["overturned"])),
                ("Still open", str(overrides["still_open"])),
            ],
            description=(
                "These counts come from simulated demo approvals and review decisions. "
                "Golden accuracy uses its own set of labels."
            ),
        ),
        failures(
            (
                ("Golden", golden),
                ("Golden v2-semantic", semantic),
                ("Fuzz", fuzz),
                ("Fuzz v2-semantic", fuzz_semantic),
            )
        ),
        table(
            "ablations",
            "Ablations",
            ("Configuration", *CALL_METRICS, "Finding-level recall"),
            [
                (run["label"], *call_metrics(run), percent(run["finding_level"]["recall"]))
                for run in (golden, *results["ablations"])
            ],
        ),
    ]
    if extraction_quality := results.get("extraction_quality"):
        sections[1:1] = [
            table(
                "extractor-quality",
                "Extractor quality",
                ("Extractor", *EXTRACTION_METRICS),
                [
                    (summary["label"], *extraction_metrics(summary["overall"]))
                    for summary in extraction_quality
                ],
                description=(
                    f"Transcript extraction across {extraction_quality[0]['calls']} golden calls "
                    "from both agent versions. Precision is the share of extracted claims that "
                    "match a reviewed identity. Recall is the share of reviewed claims recovered. "
                    "The dash marks an undefined rate."
                ),
            ),
            *[
                table(
                    f"extractor-claim-types-{index}",
                    f"Extraction by claim type · {summary['label']}",
                    ("Claim type", *EXTRACTION_METRICS),
                    [
                        (claim_type, *extraction_metrics(counts))
                        for claim_type, counts in sorted(summary["by_claim_type"].items())
                    ],
                    keep_columns=True,
                )
                for index, summary in enumerate(extraction_quality, start=1)
            ],
        ]
    return PAGE.format(
        date=check_in_date or "Unavailable",
        fingerprint=fingerprint,
        content="\n".join(sections),
    )


def export(source: Path = SOURCE, demo: Path = DEMO, *, fuzz_sweep: Path = FUZZ_SWEEP) -> None:
    raw = source.read_bytes()
    results = json.loads(raw)
    fingerprint = hashlib.sha256(raw).hexdigest()
    check_in_date = CHECK_IN_DATES.get(fingerprint)
    previous = demo / "data-evals" / "scorecard.json"
    if check_in_date is None and previous.exists():
        # Same results bytes as the last export: keep that export's date.
        old = json.loads(previous.read_text(encoding="utf-8")).get("provenance", {})
        if old.get("sha256") == fingerprint:
            check_in_date = old.get("check_in_date")
    if check_in_date is None:
        # New results (eval re-run): date them from this export.
        check_in_date = datetime.now(UTC).date().isoformat()
    overrides = score_overrides(OVERRIDES)
    sweep = json.loads(fuzz_sweep.read_text(encoding="utf-8"))
    page = render(results, check_in_date, fingerprint, overrides, sweep)
    scorecard = {
        "provenance": {
            "source": "evals/results/latest.json",
            "check_in_date": check_in_date,
            "sha256": fingerprint,
        },
        "results": results,
        "simulated_human_overrides": overrides,
        "claim_accuracy": {
            "columns": CLAIM_ACCURACY_COLUMNS,
            "by_agent_version": claim_accuracy_by_version(results),
        },
    }
    data = demo / "data-evals"
    data.mkdir(parents=True, exist_ok=True)
    (data / "scorecard.json").write_text(
        json.dumps(scorecard, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    if demo.resolve() != DEMO.resolve():
        copyfile(DEMO / "print.css", demo / "print.css")
    (demo / "evals.html").write_text(page, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    export()
