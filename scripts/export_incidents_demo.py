def export(out: Path = DEFAULT_OUT) -> None:
    first = Scenario(
        id="saga-callback-1",
        title="Billing callback",
        story="The caller asks for a billing callback.",
        steps=(Handoff(reason="call back about billing", priority="urgent"),),
        expected_claims=(("HandoffCreated", VerdictStatus.VERIFIED),),
    )
    second = replace(first, id="saga-callback-2")
    third = replace(
        first,
        id="saga-callback-3",
        steps=(*first.steps, Handoff(reason="call back about a prescription refill")),
        expected_claims=(
            ("HandoffCreated", VerdictStatus.NOT_FOUND),
            ("HandoffCreated", VerdictStatus.VERIFIED),
        ),
        faults={0: frozenset({FaultMode.PHANTOM_HANDOFF})},
        followups=(Followup(minutes_after=30, close=True, all_open_for_caller=True),),
        audit_delay_min=90,
    )
    saga = run_saga(
        [SagaCall(first, CALL_START), SagaCall(second, at(1, 9, 5)), SagaCall(third, at(2, 9, 5))],
        extractor=RuleBasedExtractor(),
    )

    (incident,) = saga.incidents
    reports = {run.report.audit_id: run.report for run in saga.runs}
    calls = []
    for linked in incident.calls:
        report = reports[linked.audit_id]
        calls.append(
            {
                **linked.model_dump(mode="json"),
                "started_at": report.call.started_at.isoformat(),
                "outcome": report.outcome.value,
                "verdicts": [
                    {"status": verdict.status.value, "utterance": verdict.claim.utterance}
                    for verdict in report.verdicts
                    if verdict.claim.claim_id in linked.claim_ids
                ],
            }
        )

    data = {
        **incident.model_dump(mode="json", exclude={"calls"}),
        "calls": calls,
        "as_of": max(report.created_at for report in reports.values()).isoformat(),
    }
    data_file = out / DATA_PATH
    data_file.parent.mkdir(parents=True, exist_ok=True)
    data_file.write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    (out / "incidents.html").write_text(
        PAGE.replace("@DATA_PATH@", DATA_PATH), encoding="utf-8", newline="\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Demo output directory")
    export(parser.parse_args().out)
