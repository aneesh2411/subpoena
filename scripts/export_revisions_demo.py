#!/usr/bin/env python3
"""Replay one call and export its signed verdict revision."""

from __future__ import annotations

import argparse
import json
from contextlib import closing
from datetime import UTC, timedelta
from pathlib import Path
from unittest.mock import patch

from subpoena.api.store import AuditStore
from subpoena.auditor import GENESIS, Auditor, RuleBasedExtractor, Sealer
from subpoena.models import VerdictStatus
from subpoena.scenarios.world import CLINIC, Scenario, build_world, run_suspect
from subpoena.suspect import AGENT_ID, FaultMode, Handoff

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "demo"
DATA_PATH = "data-revisions/revisions.json"
SEALING_KEY = b"subpoena-revisions-demo"


def replay() -> dict:
    handoff = Handoff(reason="call back about billing", priority="urgent")
    scenario = Scenario(
        id="revisions-demo",
        title="Late billing handoff",
        story="The agent promises a billing callback before the ticket lands.",
        steps=(handoff,),
        expected_claims=(("HandoffCreated", VerdictStatus.NOT_FOUND),),
        faults={0: frozenset({FaultMode.PHANTOM_HANDOFF})},
    )
    world = build_world(scenario)
    sealer = Sealer(SEALING_KEY)
    extractor = RuleBasedExtractor()
    with closing(world.store), closing(AuditStore()) as ledger:
        call = run_suspect(scenario, world).call
        ledger.save_call(call)

        def audit(audit_id: str, seconds_after: int) -> None:
            audited_at = call.ended_at + timedelta(seconds=seconds_after)
            reader = world.store.session("auditor", lambda: audited_at)
            report = Auditor(
                reader, clinic=CLINIC, extractor=extractor, clock=lambda: audited_at
            ).audit(call, audit_id=audit_id)
            # Freeze the journal clock to the simulated audit time for a stable signature.
            with patch("subpoena.api.revisions.utcnow", return_value=audited_at.astimezone(UTC)):
                ledger.append(report, sealer, revision_key=SEALING_KEY)

        audit("aud-revisions-first", 5)

        # The write arrives after the first audit, inside the default 30-second grace period.
        arrival = call.ended_at + timedelta(seconds=15)
        writer = world.store.session(f"{AGENT_ID}:{call.call_id}", lambda: arrival)
        (patient,) = writer.crm.find_patients(phone=call.caller.phone)
        ticket = writer.tickets.create_ticket(
            patient_id=patient.id, summary=handoff.reason, priority=handoff.priority
        )

        audit("aud-revisions-second", 25)
        return {
            "audits": [report.model_dump(mode="json") for report in ledger.audits()],
            "ticket": ticket.model_dump(mode="json"),
            "genesis": GENESIS,
            "journal": ledger.list_revisions(SEALING_KEY),
        }


def export(out: Path = DEFAULT_OUT) -> None:
    data_file = out / DATA_PATH
    data_file.parent.mkdir(parents=True, exist_ok=True)
    data_file.write_text(
        json.dumps(replay(), indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    (out / "revisions.html").write_text(
        PAGE.replace("@DATA_PATH@", DATA_PATH), encoding="utf-8", newline="\n"
    )


