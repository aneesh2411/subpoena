#!/usr/bin/env python3
"""Bake the rollback call's SQLite change feed and render its offline ledger."""

from __future__ import annotations

import argparse
import json
from html import escape
from pathlib import Path
from typing import Any

from subpoena.models import Change
from subpoena.scenarios.golden import BY_ID
from subpoena.scenarios.world import build_world, run_suspect

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "demo"
SCENARIO_ID = "fault-rollback"
DATA_FILE = f"data-ledger/{SCENARIO_ID}.json"


def replay() -> list[Change]:
    scenario = BY_ID[SCENARIO_ID]
    world = build_world(scenario)
    try:
        call = run_suspect(scenario, world).call
        reader = world.store.session("auditor", world.clock)
        feeds = (
            reader.calendar,
            reader.crm,
            reader.messages,
            reader.tickets,
            reader.payments,
            reader.prescriptions,
        )
        return sorted(
            (
                change
                for feed in feeds
                if feed is not None
                for change in feed.changes(call.started_at, call.ended_at)
            ),
            key=lambda change: change.seq,
        )
    finally:
        world.store.close()


def json_value(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def cell(image: dict[str, Any], field: str, changed: bool) -> str:
    if field not in image:
        return '<td><span class="missing" aria-label="Absent">—</span></td>'
    value = f"<code>{escape(json_value(image[field]))}</code>"
    if changed:
        value = f"<mark>{value}</mark>"
    return f"<td>{value}</td>"


def render_entry(entry: dict[str, Any]) -> str:
    before, after = entry["before"] or {}, entry["after"] or {}
    rows = []
    for field in sorted(before.keys() | after.keys()):
        changed = (
            field not in before
            or field not in after
            or json_value(before[field]) != json_value(after[field])
        )
        rows.append(
            f'<tr><th scope="row">{escape(field)}</th>'
            f"{cell(before, field, changed)}{cell(after, field, changed)}</tr>"
        )
    fields = "\n".join(rows)
    seq = entry["seq"]
    op, entity, entity_id, actor, at = (
        escape(entry[key]) for key in ("op", "entity", "entity_id", "actor", "at")
    )
    return f"""    <li>
      <article aria-labelledby="entry-{seq}">
        <h2 id="entry-{seq}">#{seq} <span class="operation {op}">{op}</span></h2>
        <dl>
          <div><dt>Entity</dt><dd>{entity} · <code>{entity_id}</code></dd></div>
          <div><dt>Actor</dt><dd><code>{actor}</code></dd></div>
          <div><dt>Timestamp</dt><dd><time datetime="{at}">{at}</time></dd></div>
        </dl>
        <table aria-labelledby="entry-{seq}">
          <thead><tr><th scope="col">Field</th><th scope="col">Before</th>
            <th scope="col">After</th></tr></thead>
          <tbody>
{fields}
          </tbody>
        </table>
      </article>
    </li>"""


def export(out: Path = DEFAULT_OUT) -> None:
    data_path = out / DATA_FILE
    data_path.parent.mkdir(parents=True, exist_ok=True)
    entries = [change.model_dump(mode="json") for change in replay()]
    baked = json.dumps(entries, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    data_path.write_bytes(baked.encode("utf-8"))
    ledger = "\n".join(render_entry(entry) for entry in json.loads(baked))
    page = PAGE.replace("@DATA_FILE@", DATA_FILE).replace("@LEDGER@", ledger)
    (out / "ledger.html").write_bytes(page.encode("utf-8"))


