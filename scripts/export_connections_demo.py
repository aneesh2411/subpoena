#!/usr/bin/env python3
"""Bake the Connections demo from offline golden scenario audits."""

from __future__ import annotations

import argparse
import json
from html import escape
from pathlib import Path

from subpoena.scenarios.golden import BY_ID
from subpoena.scenarios.world import run_scenario

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "demo"
DATA = "data-connections/connections.json"
SCENARIOS = {
    "clean-book": "Fully readable",
    "edge-calendar-outage": "Calendar outage",
    "edge-crm-outage": "CRM outage",
    "edge-message-log-outage": "Message log outage",
}
ADAPTERS = {
    "calendar": "Calendar",
    "crm": "CRM",
    "messages": "Message log",
    "tickets": "Tickets",
    "payments": "Payments",
    "prescriptions": "Prescriptions",
}


def snapshot(scenario_id: str, title: str) -> dict:
    report = run_scenario(BY_ID[scenario_id]).report
    audited_at = report.created_at.isoformat()
    unavailable = {gap.source: gap for gap in report.coverage_gaps if gap.kind == "unavailable"}
    adapters = []
    for source, name in ADAPTERS.items():
        gap = unavailable.get(source)
        adapters.append(
            {
                "source": source,
                "name": name,
                "status": "unreadable" if gap else "readable",
                "last_successful_read": None if gap else audited_at,
                "outage": {"name": title, "detail": gap.detail} if gap else None,
                "verdicts": [
                    {
                        "claim_id": verdict.claim.claim_id,
                        "claim": verdict.claim.type,
                        "status": verdict.status.value,
                        "summary": verdict.summary,
                    }
                    for verdict in report.verdicts
                    if gap
                    and verdict.claim.claim_id in gap.claim_ids
                    and verdict.status.value == "UNVERIFIABLE"
                ],
            }
        )
    return {"id": scenario_id, "title": title, "audited_at": audited_at, "adapters": adapters}


def render_table(scenario: dict) -> str:
    rows = []
    for adapter in scenario["adapters"]:
        stamp = adapter["last_successful_read"]
        last_read = (
            f'<time datetime="{stamp}">{stamp[:10]}<br>{stamp[11:]}</time>'
            if stamp
            else "None recorded"
        )
        status = adapter["status"]
        rows.append(
            f'        <tr><th scope="row">{escape(adapter["name"])}</th>'
            f'<td class="{status}">{status.capitalize()}</td><td>{last_read}</td></tr>'
        )
        if outage := adapter["outage"]:
            details = "".join(
                f"<li><strong>{escape(verdict['claim'])} · {verdict['status']}</strong><br>"
                f"{escape(verdict['summary'])}</li>"
                for verdict in adapter["verdicts"]
            )
            verdicts = f"<ul>{details}</ul>" if details else "<p>No verdicts affected.</p>"
            rows.append(
                '        <tr class="outage"><td colspan="3">'
                f"<strong>{escape(outage['name'])}</strong> · {escape(outage['detail'])}"
                f"{verdicts}</td></tr>"
            )
    body = "\n".join(rows)
    return f"""    <table id="{escape(scenario["id"])}">
      <caption>{escape(scenario["title"])}</caption>
      <thead>
        <tr><th scope="col">Adapter</th><th scope="col">Status</th>
          <th scope="col">Last successful read</th></tr>
      </thead>
      <tbody>
{body}
      </tbody>
    </table>"""


def export(out: Path = DEFAULT_OUT) -> None:
    scenarios = [snapshot(scenario_id, title) for scenario_id, title in SCENARIOS.items()]
    data_path = out / DATA
    data_path.parent.mkdir(parents=True, exist_ok=True)
    data_path.write_text(json.dumps(scenarios, indent=2) + "\n", encoding="utf-8", newline="\n")
    tables = "\n".join(render_table(scenario) for scenario in scenarios)
    (out / "connections.html").write_text(
        PAGE.replace("<!-- tables -->", tables), encoding="utf-8", newline="\n"
    )


