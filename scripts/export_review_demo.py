def review_sagas() -> tuple[SagaRun, ...]:
    billing = Scenario(
        id="review-shared-phone-1",
        title="Billing callback",
        story="The caller asks for a billing callback.",
        steps=(Handoff(reason="billing", ticket_topic="billing"),),
        expected_claims=(("HandoffCreated", VerdictStatus.VERIFIED),),
    )
    shared_phone = replace(
        billing, id="review-shared-phone-2", caller=PatientRef(name="Mina Chen", phone=MAYA.phone)
    )
    missing_phone = replace(billing, id="review-missing-phone-2", caller=PatientRef(name=MAYA.name))
    payment = replace(
        billing, id="review-topic-1", steps=(Handoff(reason="billing invoice payment"),)
    )
    coverage = replace(
        billing,
        id="review-topic-2",
        steps=(Handoff(reason="billing invoice coverage"),),
        faults={0: frozenset({FaultMode.PHANTOM_HANDOFF})},
        expected_claims=(("HandoffCreated", VerdictStatus.NOT_FOUND),),
    )
    return tuple(
        run_saga(
            [SagaCall(first, CALL_START), SagaCall(second, at(1, 9, 5))],
            extractor=RuleBasedExtractor(),
        )
        for first, second in (
            (billing, shared_phone),
            (replace(billing, id="review-missing-phone-1"), missing_phone),
            (payment, coverage),
        )
    )


def export(out: Path = DEFAULT_OUT) -> None:
    reviews = []
    for saga in review_sagas():
        reports = {run.report.audit_id: run.report for run in saga.runs}
        for review in saga.reviews:
            calls = sorted(
                (reports[audit_id] for audit_id in review.audits),
                key=lambda report: (report.call.started_at, report.audit_id),
            )
            reviews.append(
                {
                    **review.model_dump(mode="json"),
                    "calls": [
                        {
                            "audit_id": report.audit_id,
                            "started_at": report.call.started_at.isoformat(),
                            "outcome": report.outcome.value,
                        }
                        for report in calls
                    ],
                }
            )

    booking = Book(start=at(2, 10), provider=PATEL, confirm=False)
    assignment = Scenario(
        id="review-ambiguous-assignment",
        title="Two claims for one booking",
        story="The first booking rolled back before the agent repeated the same booking.",
        steps=(booking, booking),
        expected_claims=(("AppointmentBooked", VerdictStatus.UNVERIFIABLE),) * 2,
        faults={0: frozenset({FaultMode.ROLLBACK})},
    )
    audit = run_scenario(assignment).report
    assignment_items = [item.model_dump(mode="json") for item in audit_items(audit)]

    data_file = out / DATA_PATH
    data_file.parent.mkdir(parents=True, exist_ok=True)
    data_file.write_text(
        json.dumps(
            {"reviews": reviews, "assignment_items": assignment_items}, indent=2, sort_keys=True
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    (out / AUDIT_PATH).write_text(
        audit.model_dump_json(indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    (out / "review.html").write_text(
        PAGE.replace("@DATA_PATH@", DATA_PATH).replace("@AUDIT_PATH@", AUDIT_PATH),
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Demo output directory")
    export(parser.parse_args().out)
