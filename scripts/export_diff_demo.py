DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "demo"
SCENARIO_ID = "fault-wrong-time"
SEALING_KEY = b"subpoena-pages-demo"


def changed_fields(
    before: dict[str, Any], after: dict[str, Any], kind: str
) -> list[dict[str, Any]]:
    return [
        {"kind": kind, "field": field, "before": before.get(field), "after": after.get(field)}
        for field in sorted(before.keys() | after.keys())
        if field not in before or field not in after or _json(before[field]) != _json(after[field])
    ]


def write_json(path: Path, value: Any) -> None:
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def export(out: Path = DEFAULT_OUT) -> None:
    data_dir = out / "data-diff"
    data_dir.mkdir(parents=True, exist_ok=True)
    fault = BY_ID[SCENARIO_ID]
    corrected = replace(fault, faults={})
    extractor, sealer = RuleBasedExtractor(), Sealer(SEALING_KEY)
    reports = []
    outcomes = {}
    for label, scenario in (("before", fault), ("after", corrected)):
        report = run_scenario(scenario, extractor=extractor, sealer=sealer).report
        path = data_dir / f"{label}.json"
        write_json(path, report.model_dump(mode="json"))
        checked_report, status = _verify(path, sealer)
        if checked_report is None:
            raise ValueError(f"{label} seal: {status}")
        reports.append(checked_report)
        outcomes[label] = {
            "outcome": checked_report.outcome.value,
            "seal": status,
        }

    write_json(data_dir / "diff.json", comparison(fault.id, *reports, outcomes))
    export_reaudit(data_dir)
    (out / "audit-diff.html").write_text(PAGE, encoding="utf-8")


def comparison(
    scenario_id: str, before: AuditReport, after: AuditReport, outcomes: dict[str, Any]
) -> dict[str, Any]:
    old_verdicts, new_verdicts = _index(before), _index(after)
    if before.call.call_id != after.call.call_id or old_verdicts.keys() != new_verdicts.keys():
        raise ValueError("The demo requires matching call and claim IDs across the replay.")

    claims = []
    for claim_id in sorted(old_verdicts):
        old, new = old_verdicts[claim_id], new_verdicts[claim_id]
        fields = changed_fields(
            old.claim.model_dump(mode="json", exclude={"claim_id"}),
            new.claim.model_dump(mode="json", exclude={"claim_id"}),
            "claim",
        )
        fields.extend(changed_fields(_field_rows(old), _field_rows(new), "receipt"))
        claims.append(
            {
                "claim_id": claim_id,
                "claim_type": type(old.claim).__name__,
                "before": old.status.value,
                "after": new.status.value,
                "fields": fields,
            }
        )

    return {
        "scenario_id": scenario_id,
        "call_id": before.call.call_id,
        "runs": outcomes,
        "claims": claims,
        "cli_diff": _diff(before, after),
    }


def export_reaudit(data_dir: Path) -> None:
    run = replay()
    sealer = Sealer(REVISION_KEY)
    reports = []
    outcomes = {}
    previous = GENESIS
    for side, payload in zip(("before", "after"), run["audits"], strict=True):
        report = AuditReport.model_validate(payload)
        check = sealer.verify(report, expected_prev=previous)
        if not check.ok or report.seal is None:
            raise ValueError(f"{side} re-audit seal: {check.reason}")
        filename = f"reaudit-{side}.json"
        write_json(data_dir / filename, payload)
        reports.append(report)
        outcomes[side] = {
            "outcome": report.outcome.value,
            "seal": f"OK integrity={check.integrity} authentication={check.authentication}"
            f" ({check.reason})",
            "file": filename,
            "audit_id": report.audit_id,
            "call_id": report.call.call_id,
            "chain_hash": report.seal.chain_hash,
        }
        previous = report.seal.chain_hash
    write_json(
        data_dir / "reaudit.json",
        {**comparison("revisions-demo", *reports, outcomes), "journal": run["journal"]},
    )


